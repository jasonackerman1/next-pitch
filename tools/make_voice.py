"""Records Skip's voice for every card (edge-tts, a free Microsoft neural voice).

Run after changing any card text, or the shared lines in js/voice.js:
    .venv/bin/python tools/make_voice.py
(one-time setup: python3 -m venv .venv && .venv/bin/pip install edge-tts; ffmpeg needed)

Each clip is named by a hash of its spoken text + voice, so only new or changed lines get
recorded; clips nobody uses anymore are deleted. Writes audio/*.mp3 and js/voice-manifest.js.
"""
import asyncio
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import edge_tts

VOICE = 'en-US-AndrewNeural'
RATE = '+6%'
ROOT = Path(__file__).resolve().parent.parent
AUDIO = ROOT / 'audio'
MANIFEST = ROOT / 'js' / 'voice-manifest.js'

NUM = {'0': 'oh', '1': 'one', '2': 'two', '3': 'three', '4': 'four', '5': 'five', '6': 'six', '7': 'seven', '8': 'eight', '9': 'nine'}


def spoken(text):
    """How a line should SOUND (the screen text stays as written)."""
    t = text
    # Scorebook plays: "6-4-3" → "six, four, three".
    t = re.sub(r'\b\d(?:-\d){1,3}\b(?=["\s]*(?:double|groundout|"))', lambda m: ', '.join(NUM[d] if d != '0' else 'zero' for d in m.group(0).split('-')), t)
    # Counts: "3-1" → "three and one", "0-2" → "oh and two".
    t = re.sub(r'\b([0-3])-([0-2])\b', lambda m: f'{NUM[m.group(1)]} and {NUM[m.group(2)]}', t)
    t = t.replace('GHVBL', 'G.H.V.B.L.')
    # Words in CAPS are emphasis on screen; read them as words, not letters.
    t = re.sub(r'\b[A-Z]{2,}\b', lambda m: m.group(0).lower(), t)
    t = re.sub(r'\s*[—–]\s*', ', ', t).replace('/', ' or ')
    t = re.sub(r'\bft\b', 'feet', t)
    return re.sub(r'\s+', ' ', t).strip()


def clip_name(text):
    return hashlib.sha1(f'{VOICE}|{RATE}|{text}'.encode()).hexdigest()[:14] + '.mp3'


async def record(text, dest, sem):
    async with sem:
        with tempfile.NamedTemporaryFile(suffix='.mp3', delete=False) as tmp:
            raw = Path(tmp.name)
        for attempt in range(4):
            try:
                await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(raw))
                break
            except Exception as err:  # the service hiccups now and then
                if attempt == 3:
                    raise
                print(f'  retry ({err}): {text[:50]}')
                await asyncio.sleep(2 + attempt * 2)
        # Mono 32 kbps is plenty for speech and keeps the app small.
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(raw), '-ac', '1', '-b:a', '32k', str(dest)], check=True)
        raw.unlink()


async def main():
    lines = json.loads(subprocess.run(['node', str(ROOT / 'tools' / 'voice_lines.mjs')], capture_output=True, text=True, check=True).stdout)
    AUDIO.mkdir(exist_ok=True)
    manifest = {}
    todo = {}
    for line in lines:
        say = spoken(line['text'])
        name = clip_name(say)
        manifest[line['key']] = name
        if not (AUDIO / name).exists():
            todo[name] = say
    print(f'{len(lines)} lines, {len(set(manifest.values()))} clips, {len(todo)} to record')
    sem = asyncio.Semaphore(6)
    done = 0
    async def one(name, say):
        nonlocal done
        await record(say, AUDIO / name, sem)
        done += 1
        if done % 50 == 0:
            print(f'  {done}/{len(todo)}')
    await asyncio.gather(*(one(n, s) for n, s in todo.items()))

    keep = set(manifest.values())
    stale = [f for f in AUDIO.glob('*.mp3') if f.name not in keep]
    for f in stale:
        f.unlink()
    body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k, v in sorted(manifest.items()))
    MANIFEST.write_text('// Generated by tools/make_voice.py. Do not edit by hand.\n// Line key → recorded clip in audio/.\nexport const VOICE = {\n' + body + ',\n};\n')
    size = sum(f.stat().st_size for f in AUDIO.glob('*.mp3'))
    print(f'Done. {len(keep)} clips, {size / 1e6:.1f} MB, removed {len(stale)} unused.')


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == '--sample':
        # Hear one line before recording everything: tools/make_voice.py --sample "text" out.mp3
        asyncio.run(edge_tts.Communicate(spoken(sys.argv[2]), VOICE, rate=RATE).save(sys.argv[3]))
    else:
        asyncio.run(main())
